"""Write the Sobol direction-number table (Joe and Kuo, new-joe-kuo-6.21201, as packaged in SciPy)
for the first DIMS dimensions as a C++ header for nav2_mppi_controller.

  uv run --with scipy python make_sobol_header.py OUT.hpp [dims]

poly[d]: the primitive polynomial x^s + a_1 x^(s-1) + ... + a_(s-1) x + 1 as an integer, bit j =
coefficient of x^j (so the degree is bit_length - 1); minit[d][k]: the initial m_1..m_s.
Dimension 0 is the van der Corput sequence (poly = 1, no initial numbers).
"""

import os
import sys

import numpy as np
import scipy
import scipy.stats._sobol as sobol_mod

out = sys.argv[1]
dims = int(sys.argv[2]) if len(sys.argv) > 2 else 112
z = np.load(os.path.join(os.path.dirname(sobol_mod.__file__), "_sobol_direction_numbers.npz"))
poly = z["poly"][:dims].astype(int)
vinit = z["vinit"][:dims].astype(int)
deg = max(int(p).bit_length() - 1 for p in poly)
lines = [
    "// Generated by make_sobol_header.py from SciPy " + scipy.__version__ + " (_sobol_direction_numbers.npz).",
    "// Sobol direction numbers of S. Joe and F. Y. Kuo, \"Constructing Sobol sequences with better",
    "// two-dimensional projections\", SIAM J. Sci. Comput. 30(5) (2008) 2635-2654,",
    "// DOI 10.1137/070709359, file new-joe-kuo-6.21201. Licence terms of the table: not checked",
    "// in this lab; check them before proposing this upstream.",
    "#pragma once",
    "#include <cstdint>",
    "namespace mppi::sobol",
    "{",
    f"constexpr int kMaxDim = {dims};",
    f"constexpr int kMaxDeg = {deg};",
    "constexpr uint32_t kPoly[kMaxDim] = {",
]
for i in range(0, dims, 12):
    lines.append("  " + ", ".join(str(p) for p in poly[i:i + 12]) + ",")
lines += ["};", "constexpr uint32_t kMinit[kMaxDim][kMaxDeg] = {"]
for d in range(dims):
    lines.append("  {" + ", ".join(str(v) for v in vinit[d, :deg]) + "},")
lines += ["};", "}  // namespace mppi::sobol", ""]
open(out, "w").write("\n".join(lines))
print(f"{out}: {dims} dims, max degree {deg}")
